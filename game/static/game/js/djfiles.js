// Vazifa eski qatorni almashtiradi (yangisi yozilgach, eskisi qolmasligi kerak)
export const REPLACES = {
  set_paths: ['"DIRS": [],'],
  conf_urls: ["from django.urls import path"],
};

const fillV = (s, v) => s.replace(/\{(\w+)\}/g, (m, k) => (v[k] !== undefined ? v[k] : m));

// Solishtirish: bo'sh joylar va qo'shtirnoq turi farq qilmasin
export const norm = (s) => String(s).replace(/'/g, '"').replace(/\s+/g, " ").trim().replace(/,$/, "");

export function baseLines(path, v) {
  const b = BASE[path];
  return b === undefined ? null : fillV(b, v).split("\n");
}

// Vazifani faylga qo'llash ("Yozib ber" va oldingi qadamlarni tiklash uchun)
// Faqat "Yozib ber" uchun: Django qo'ygan "# Create your ... here." izohini olib tashlaymiz (majburiy emas)
const TIDY = ["# Create your views here.", "# Create your models here.", "# Register your models here."];

export function applyTask(lines, t, v) {
  // yangi (bo'sh) fayl — namunaning o'zi
  if (!lines.some((l) => l.trim())) return t.code.filter((l) => l.trim() !== "...").map((l) => fillV(l.startsWith("+") ? l.slice(1) : l, v));
  const out = lines.filter((l) => !TIDY.includes(l.trim()));
  while (out.length > 1 && !out[out.length - 1].trim() && !out[out.length - 2].trim()) out.pop();
  (REPLACES[t.id] || []).forEach((old) => {
    const k = out.findIndex((l) => norm(l) === norm(old));
    if (k >= 0) out.splice(k, 1);
  });
  let at = -1, blanks = 0, delta = 0;              // oxirgi qator; namunadagi bo'sh qatorlar; chekinish farqi
  const ind = (s) => s.length - s.trimStart().length;
  const shift = (s) => (delta > 0 ? " ".repeat(delta) + s : delta < 0 ? s.slice(Math.min(-delta, ind(s))) : s);
  t.code.forEach((raw) => {
    const line = fillV(raw, v);
    if (line.trim() === "...") return;
    if (line.startsWith("+")) {
      const text = shift(line.slice(1));
      const exist = out.findIndex((l, k) => k > at && norm(l) === norm(text));
      if (exist >= 0) { at = exist; blanks = 0; return; }
      // namunadagidek bo'sh qatorlar (allaqachon bo'lganini hisobga olib)
      let have = 0;
      while (have < blanks && out[at + 1 + have] !== undefined && !out[at + 1 + have].trim()) have += 1;
      for (let b = have; b < blanks; b++) out.splice(at + 1 + b, 0, "");
      at += blanks;
      out.splice(at + 1, 0, text);
      at += 1;
      blanks = 0;
      return;
    }
    if (!line.trim()) { blanks += 1; return; }
    const k = out.findIndex((l, j) => j > at && norm(l) === norm(line));
    if (k >= 0) { at = k; delta = ind(out[k]) - ind(line); }
    blanks = 0;
  });
  // yangi fayl / oxirgi qator: ortiqcha bo'sh qatorlarni yig'ishtiramiz
  while (out.length > 1 && !out[out.length - 1].trim() && !out[out.length - 2].trim()) out.pop();
  return out;
}

// O'yinchi yozgan faylni tekshirish: har "+" qator bormi va to'g'ri joydami (oldingi qatordan keyin)
export function checkFile(lines, t, v) {
  const problems = [];
  let at = -1, anchor = "";
  for (const raw of t.code) {
    const line = fillV(raw, v);
    if (line.trim() === "..." || (!line.startsWith("+") && !line.trim())) continue;
    const plus = line.startsWith("+");
    const text = plus ? line.slice(1) : line;
    const k = lines.findIndex((l, j) => j > at && norm(l) === norm(text));
    if (k < 0) {
      const anywhere = lines.findIndex((l) => norm(l) === norm(text));
      if (plus) {
        problems.push(anywhere >= 0
          ? `"${text.trim()}" — bor, lekin joyi noto'g'ri: "${anchor.trim() || "fayl boshi"}" dan keyin bo'lsin`
          : `Yetishmaydi: ${text.trim()}${anchor ? `   (qayerga: "${anchor.trim()}" dan keyin)` : ""}`);
      }
      continue;          // kontekst qatori (namunada soddalashtirilgan bo'lishi mumkin) — tekshirmaymiz
    }
    at = k;
    anchor = text;
  }
  (REPLACES[t.id] || []).forEach((old) => {
    if (lines.some((l) => norm(l) === norm(old))) problems.push(`Eski qatorni o'chiring (yangisi bilan almashtiring): ${old}`);
  });
  return problems;
}
